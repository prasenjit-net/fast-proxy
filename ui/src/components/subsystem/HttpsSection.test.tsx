import { screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, describe, expect, it, vi } from "vitest";
import { certificate, envelope, httpsSettings, subsystemDetail, tlsStatus } from "../../test/fixtures";
import { apiError, mockApi, type Reply } from "../../test/mockApi";
import { renderPage } from "../../test/renderPage";
import type { HttpsSettings } from "../../lib/types";
import HttpsSection from "./HttpsSection";

const cert = "-----BEGIN CERTIFICATE-----\nAAAA\n-----END CERTIFICATE-----";
const key = "-----BEGIN PRIVATE KEY-----\nBBBB\n-----END PRIVATE KEY-----";
const written: Reply = { body: envelope(subsystemDetail(), 6) };

function attached(overrides: Partial<NonNullable<HttpsSettings["certificate"]>> = {}) {
  return {
    name: "shop",
    source: "uploaded" as const,
    notAfterMs: Date.now() + 90 * 86_400_000,
    uncoveredHosts: [],
    ...overrides,
  };
}

function renderSection(https: HttpsSettings, handlers: Record<string, Reply> = {}, tlsOn = true) {
  const api = mockApi({
    "GET /api/tls": { body: envelope(tlsStatus({ enabled: tlsOn })) },
    "GET /api/certificates": {
      body: envelope([certificate({ id: 3, name: "shop" }), certificate({ id: 4, name: "wild", names: ["*.example.com"] })]),
    },
    ...handlers,
  });
  const detail = subsystemDetail({ https });
  renderPage(() => <HttpsSection subsystem={detail} />, { path: "/x", entry: "/x" });
  return api;
}

const dialog = () => within(screen.getByRole("dialog"));
const on = (overrides: Partial<HttpsSettings> = {}) =>
  httpsSettings({ enabled: true, effective: true, certificateId: 3, certificate: attached(), ...overrides });

afterEach(() => {
  vi.unstubAllGlobals();
});

describe("HttpsSection", () => {
  it("says so when TLS is off for the process, and that the settings are saved but not applied", async () => {
    renderSection(on({ effective: false }), {}, false);
    expect(await screen.findByRole("note")).toHaveTextContent(/TLS is off for this proxy/);
    expect(screen.getByText("saved, not applied")).toBeInTheDocument();
  });

  it("shows the attached certificate with its source and days left", async () => {
    renderSection(on());
    expect(await screen.findByText("serving HTTPS")).toBeInTheDocument();
    expect(screen.getByRole("heading", { name: "shop", level: 3 })).toBeInTheDocument();
    expect(screen.getByText("uploaded")).toBeInTheDocument();
    expect(screen.getByText(/in 8\d days|in 90 days/)).toBeInTheDocument();
  });

  it("warns that a development certificate is not trusted, and about uncovered hosts", async () => {
    renderSection(on({ certificate: attached({ source: "self_signed", name: "dev-shop", uncoveredHosts: ["old.example.com"] }) }));
    expect(await screen.findByText(/development certificate generated by the proxy/i)).toBeInTheDocument();
    expect(screen.getByText("old.example.com")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Use a development certificate" })).not.toBeInTheDocument();
  });

  it("enables HTTPS by sending the whole subsystem with the new switch, leaving the rest as it was", async () => {
    const api = renderSection(httpsSettings(), { "PUT /api/subsystems/1": written });
    await userEvent.click(await screen.findByLabelText("Serve over HTTPS"));
    await waitFor(() => expect(api.called("PUT", "/api/subsystems/1")).toHaveLength(1));
    expect(api.called("PUT", "/api/subsystems/1")[0].body).toEqual({
      name: "shop",
      enabled: true,
      description: "The shop",
      https: {
        enabled: true,
        certificateId: null,
        redirect: "off",
        hsts: { enabled: false, maxAgeSecs: 31_536_000, includeSubdomains: false },
      },
    });
    expect(await screen.findByText("HTTPS enabled")).toBeInTheDocument();
  });

  it("shows the server's error when the switch cannot be saved", async () => {
    renderSection(httpsSettings(), { "PUT /api/subsystems/1": apiError(409, "CONFLICT", "nope") });
    await userEvent.click(await screen.findByLabelText("Serve over HTTPS"));
    expect(await screen.findByText("nope")).toBeInTheDocument();
  });

  it("uploads a certificate for this subsystem, sending the key once and clearing it", async () => {
    const api = renderSection(on(), {
      "POST /api/subsystems/1/certificate": { status: 201, body: envelope(certificate({ name: "fresh" }), 7) },
    });
    await userEvent.click(await screen.findByRole("button", { name: "Upload a certificate" }));
    await userEvent.type(dialog().getByLabelText("Name"), "fresh");
    await userEvent.click(dialog().getByLabelText("Certificate chain (PEM)"));
    await userEvent.paste(cert);
    await userEvent.click(dialog().getByLabelText("Private key (PEM)"));
    await userEvent.paste(key);
    await userEvent.click(dialog().getByRole("button", { name: "Upload and attach" }));

    expect(await screen.findByText("Certificate fresh attached")).toBeInTheDocument();
    expect(api.called("POST", "/api/subsystems/1/certificate")[0].body).toEqual({
      name: "fresh",
      certPem: cert,
      keyPem: key,
    });
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
  });

  it("shows a certificate that covers none of the hosts as an inline error", async () => {
    renderSection(on(), {
      "POST /api/subsystems/1/certificate": apiError(400, "VALIDATION_FAILED", "validation failed", [
        { field: "certPem", message: "the certificate covers none of this subsystem's hosts" },
      ]),
    });
    await userEvent.click(await screen.findByRole("button", { name: "Upload a certificate" }));
    await userEvent.type(dialog().getByLabelText("Name"), "wrong");
    await userEvent.click(dialog().getByLabelText("Certificate chain (PEM)"));
    await userEvent.paste(cert);
    await userEvent.click(dialog().getByLabelText("Private key (PEM)"));
    await userEvent.paste(key);
    await userEvent.click(dialog().getByRole("button", { name: "Upload and attach" }));
    expect(await dialog().findByText(/covers none of this subsystem's hosts/)).toBeInTheDocument();
  });

  it("attaches an existing certificate chosen from the list", async () => {
    const api = renderSection(on(), { "PUT /api/subsystems/1": written });
    await userEvent.click(await screen.findByRole("button", { name: "Choose an existing one" }));
    await dialog().findByRole("option", { name: /wild/ });
    expect(dialog().getByRole("button", { name: "Attach" })).toBeDisabled();
    await userEvent.selectOptions(dialog().getByLabelText("Certificate"), "4");
    await userEvent.click(dialog().getByRole("button", { name: "Attach" }));
    await waitFor(() => expect(api.called("PUT", "/api/subsystems/1")).toHaveLength(1));
    expect(api.called("PUT", "/api/subsystems/1")[0].body).toMatchObject({ https: { certificateId: 4 } });
  });

  it("falls back to a development certificate by detaching", async () => {
    const api = renderSection(on(), { "DELETE /api/subsystems/1/certificate": { body: { version: 8 } } });
    await userEvent.click(await screen.findByRole("button", { name: "Use a development certificate" }));
    expect(await screen.findByText("A development certificate will be used")).toBeInTheDocument();
    expect(api.called("DELETE", "/api/subsystems/1/certificate")).toHaveLength(1);
  });

  it("confirms HSTS in plain words before saving it, and sends nothing on cancel", async () => {
    const api = renderSection(on(), { "PUT /api/subsystems/1": written });
    await userEvent.click(await screen.findByLabelText("Send Strict-Transport-Security (HSTS)"));
    await userEvent.selectOptions(screen.getByLabelText("Remember HTTPS for"), "2592000");
    await userEvent.click(screen.getByLabelText("Include subdomains"));
    await userEvent.click(screen.getByRole("button", { name: "Save HTTPS settings" }));

    expect(dialog().getByText(/will remember for 30 days, for all subdomains too/)).toBeInTheDocument();
    expect(dialog().getByText(/hard to undo/)).toBeInTheDocument();
    await userEvent.click(dialog().getByRole("button", { name: "Cancel" }));
    expect(api.called("PUT", "/api/subsystems/1")).toHaveLength(0);

    await userEvent.click(screen.getByRole("button", { name: "Save HTTPS settings" }));
    await userEvent.click(dialog().getByRole("button", { name: "Apply" }));
    await waitFor(() => expect(api.called("PUT", "/api/subsystems/1")).toHaveLength(1));
    expect(api.called("PUT", "/api/subsystems/1")[0].body).toMatchObject({
      https: { hsts: { enabled: true, maxAgeSecs: 2_592_000, includeSubdomains: true } },
    });
    expect(await screen.findByText("HTTPS settings saved")).toBeInTheDocument();
  });

  it("confirms turning the redirect on, and saves lowering it without a prompt", async () => {
    const api = renderSection(on(), { "PUT /api/subsystems/1": written });
    await userEvent.selectOptions(await screen.findByLabelText("Plain HTTP requests"), "308");
    await userEvent.click(screen.getByRole("button", { name: "Save HTTPS settings" }));
    expect(dialog().getByText(/answered with a 308 redirect to HTTPS/)).toBeInTheDocument();
    await userEvent.click(dialog().getByRole("button", { name: "Apply" }));
    await waitFor(() => expect(api.called("PUT", "/api/subsystems/1")).toHaveLength(1));
    expect(api.called("PUT", "/api/subsystems/1")[0].body).toMatchObject({ https: { redirect: "308" } });
  });

  it("saves a change that turns nothing on without asking, and keeps Save off until something changed", async () => {
    const api = renderSection(
      on({ redirect: "308", hsts: { enabled: true, maxAgeSecs: 600, includeSubdomains: false } }),
      { "PUT /api/subsystems/1": written },
    );
    const save = await screen.findByRole("button", { name: "Save HTTPS settings" });
    expect(save).toBeDisabled();
    await userEvent.selectOptions(screen.getByLabelText("Plain HTTP requests"), "off");
    await userEvent.click(save);
    await waitFor(() => expect(api.called("PUT", "/api/subsystems/1")).toHaveLength(1));
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
    expect(api.called("PUT", "/api/subsystems/1")[0].body).toMatchObject({
      https: { redirect: "off", hsts: { enabled: true, maxAgeSecs: 600 } },
    });
  });

  it("hides the certificate and policy controls while HTTPS is off", async () => {
    renderSection(httpsSettings());
    expect(await screen.findByLabelText("Serve over HTTPS")).not.toBeChecked();
    expect(screen.queryByLabelText("Plain HTTP requests")).not.toBeInTheDocument();
    expect(screen.getByText("off")).toBeInTheDocument();
  });

  it("offers an upload when HTTPS is on but nothing is attached yet", async () => {
    renderSection(httpsSettings({ enabled: true, effective: false }), {}, false);
    expect(await screen.findByText(/a development certificate is generated when TLS is on/i)).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Upload a certificate" })).toBeInTheDocument();
  });
});

