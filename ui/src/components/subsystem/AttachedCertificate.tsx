import { daysLeft, expiryLabel, EXPIRING_DAYS, isSelfSigned } from "../../lib/certificates";
import type { AttachedCertificate as Attached } from "../../lib/types";
import Badge from "../Badge";
import { SourceBadge } from "../certificates/CertificateBadges";

interface Props {
  certificate: Attached;
  /** Seconds until expiry, from the server's clock at the time of the response. */
  secondsLeft: number;
  onUpload: () => void;
  onChoose: () => void;
  onUseDevelopment: () => void;
}

/** The certificate a subsystem serves, what is wrong with it, and what can be done. */
export default function AttachedCertificate({ certificate, secondsLeft, onUpload, onChoose, onUseDevelopment }: Props) {
  const selfSigned = isSelfSigned(certificate.source);
  const expiring = daysLeft(secondsLeft) < EXPIRING_DAYS;
  return (
    <div className="rounded-md border border-line p-3">
      <div className="flex flex-wrap items-center gap-2">
        <h3 className="text-[0.95rem] font-semibold">{certificate.name}</h3>
        <SourceBadge source={certificate.source} />
        <Badge tone={secondsLeft <= 0 ? "err" : expiring ? "warn" : "ok"} dot>
          {expiryLabel(secondsLeft)}
        </Badge>
      </div>
      {selfSigned ? (
        <p className="mt-2 text-[0.84rem] text-warn">
          This is a development certificate generated by the proxy. Browsers will warn visitors;
          upload a real certificate for production.
        </p>
      ) : null}
      {certificate.uncoveredHosts.length > 0 ? (
        <p className="mt-2 text-[0.84rem] text-warn">
          Does not cover: <span className="font-mono">{certificate.uncoveredHosts.join(", ")}</span>.
          Those hosts will fail certificate checks over HTTPS.
        </p>
      ) : null}
      <div className="mt-3 flex flex-wrap gap-2">
        <button type="button" className="btn btn-secondary btn-sm" onClick={onUpload}>
          Upload a certificate
        </button>
        <button type="button" className="btn btn-secondary btn-sm" onClick={onChoose}>
          Choose an existing one
        </button>
        {selfSigned ? null : (
          <button type="button" className="btn btn-secondary btn-sm" onClick={onUseDevelopment}>
            Use a development certificate
          </button>
        )}
      </div>
    </div>
  );
}
