import { useState, type FormEvent } from "react";
import {
  BODY_TYPES,
  DURATION_CHOICES,
  defaultMaintenanceValues,
  validateMaintenance,
  type MaintenanceValues,
} from "../../lib/maintenanceValidation";
import type { MaintenanceInput, MaintenanceSet } from "../../lib/types";
import { useServerErrors } from "../../lib/useServerErrors";
import FormError from "../FormError";
import FormField, { errorProps } from "../FormField";

interface MaintenanceFormProps {
  /** What is being closed, for the submit button and the hints ("subsystem shop"). */
  covers: string;
  onSubmit: (input: MaintenanceInput) => Promise<MaintenanceSet>;
  onCancel: () => void;
  /** Called with the answer, which carries the generated bypass secret, once. */
  onDone: (result: MaintenanceSet) => void;
}

/** Message, duration and bypass for turning maintenance on. */
export default function MaintenanceForm({ covers, onSubmit, onCancel, onDone }: MaintenanceFormProps) {
  const [values, setValues] = useState<MaintenanceValues>(defaultMaintenanceValues);
  const [clientErrors, setClientErrors] = useState<Record<string, string | undefined>>({});
  const [busy, setBusy] = useState(false);
  const server = useServerErrors();
  const error = (field: string) => clientErrors[field] ?? server.field(field);
  const set = <K extends keyof MaintenanceValues>(key: K, value: MaintenanceValues[K]) =>
    setValues((current) => ({ ...current, [key]: value }));

  async function handleSubmit(event: FormEvent) {
    event.preventDefault();
    server.clear();
    const result = validateMaintenance(values);
    setClientErrors(result.errors);
    if (result.value === undefined) return;
    setBusy(true);
    try {
      onDone(await onSubmit(result.value));
    } catch (thrown) {
      server.capture(thrown);
      setBusy(false);
    }
  }

  return (
    <form onSubmit={handleSubmit} noValidate className="flex flex-col gap-4">
      <FormError message={server.general} />
      <FormField
        label="Message"
        htmlFor="maintenance-message"
        error={error("message")}
        hint="Shown to visitors on the maintenance page. Optional."
      >
        <textarea
          id="maintenance-message"
          className="input"
          rows={2}
          value={values.message}
          placeholder="Back at 14:00 UTC"
          onChange={(event) => set("message", event.target.value)}
          {...errorProps("maintenance-message", error("message"))}
        />
      </FormField>

      <FormField label="How long" htmlFor="maintenance-duration" error={error("ttlSecs")}>
        <div className="flex flex-wrap gap-2">
          <select
            id="maintenance-duration"
            className="input w-auto"
            value={values.duration}
            onChange={(event) => set("duration", event.target.value)}
            {...errorProps("maintenance-duration", error("ttlSecs"))}
          >
            {DURATION_CHOICES.map((choice) => (
              <option key={choice.value} value={choice.value}>
                {choice.label}
              </option>
            ))}
          </select>
          {values.duration === "custom" ? (
            <input
              aria-label="Custom minutes"
              className="input w-32"
              inputMode="numeric"
              placeholder="minutes"
              value={values.customMinutes}
              onChange={(event) => set("customMinutes", event.target.value)}
            />
          ) : null}
        </div>
      </FormField>

      <FormField
        label="Retry-After (seconds)"
        htmlFor="maintenance-retry"
        error={error("retryAfterSecs")}
        hint="Tells clients when to come back. Empty: the time left, or two minutes."
      >
        <input
          id="maintenance-retry"
          className="input w-40"
          inputMode="numeric"
          value={values.retryAfterSecs}
          onChange={(event) => set("retryAfterSecs", event.target.value)}
          {...errorProps("maintenance-retry", error("retryAfterSecs"))}
        />
      </FormField>

      <label className="flex items-center gap-2 text-[0.85rem]">
        <input
          type="checkbox"
          checked={values.customBody}
          onChange={(event) => set("customBody", event.target.checked)}
        />
        Use my own page instead of the built-in one
      </label>
      {values.customBody ? (
        <>
          <FormField label="Content type" htmlFor="maintenance-content-type" error={error("contentType")}>
            <select
              id="maintenance-content-type"
              className="input w-auto"
              value={values.contentType}
              onChange={(event) => set("contentType", event.target.value)}
            >
              {BODY_TYPES.map((type) => (
                <option key={type} value={type}>
                  {type}
                </option>
              ))}
            </select>
          </FormField>
          <FormField label="Page" htmlFor="maintenance-body" error={error("body")} hint="At most 16 KiB.">
            <textarea
              id="maintenance-body"
              className="input font-mono text-[0.8rem]"
              rows={5}
              value={values.body}
              onChange={(event) => set("body", event.target.value)}
              {...errorProps("maintenance-body", error("body"))}
            />
          </FormField>
        </>
      ) : null}

      <fieldset className="flex flex-col gap-3 rounded-lg border border-line p-3">
        <legend className="px-1 text-[0.82rem] font-medium">Let some requests through</legend>
        <FormField
          label="Networks"
          htmlFor="maintenance-cidrs"
          error={error("bypass.cidrs")}
          hint="One per line, such as 10.0.0.0/8. Requests from these addresses are served normally."
        >
          <textarea
            id="maintenance-cidrs"
            className="input font-mono text-[0.8rem]"
            rows={2}
            value={values.cidrs}
            onChange={(event) => set("cidrs", event.target.value)}
            {...errorProps("maintenance-cidrs", error("bypass.cidrs"))}
          />
        </FormField>
        <FormField
          label="Bypass header"
          htmlFor="maintenance-header"
          error={error("bypass.header")}
          hint="A request carrying this header with the secret is served normally."
        >
          <input
            id="maintenance-header"
            className="input"
            value={values.headerName}
            placeholder="X-Maintenance-Bypass"
            onChange={(event) => set("headerName", event.target.value)}
            {...errorProps("maintenance-header", error("bypass.header"))}
          />
        </FormField>
        <FormField
          label="Secret"
          htmlFor="maintenance-secret"
          error={error("bypass.secret")}
          hint="Leave empty to generate one; it is shown once, after you turn maintenance on."
        >
          <input
            id="maintenance-secret"
            className="input font-mono text-[0.82rem]"
            autoComplete="off"
            value={values.secret}
            onChange={(event) => set("secret", event.target.value)}
            {...errorProps("maintenance-secret", error("bypass.secret"))}
          />
        </FormField>
      </fieldset>

      <div className="flex justify-end gap-2">
        <button type="button" className="btn btn-secondary" onClick={onCancel} disabled={busy}>
          Cancel
        </button>
        <button type="submit" className="btn btn-danger" disabled={busy}>
          Turn on for {covers}
        </button>
      </div>
    </form>
  );
}
