#!/usr/bin/env bash
# Prints the Homebrew formula for one release (ADR 0033).
#
#   scripts/homebrew-formula.sh VERSION DIST_DIR REPOSITORY > Formula/fast-proxy.rb
#
# VERSION is MAJOR.MINOR.PATCH, DIST_DIR holds the release archives' .sha256
# files, REPOSITORY is owner/name on GitHub. macOS uses the Apple builds, Linux
# the static musl ones.
set -euo pipefail

if [ "$#" -ne 3 ]; then
  echo "usage: $0 VERSION DIST_DIR REPOSITORY" >&2
  exit 2
fi
version="$1"
dist="$2"
repository="$3"
tag="v${version}"

# The SHA-256 of one target's archive, from the .sha256 file the build wrote.
checksum() {
  local file="${dist}/fast-proxy-${tag}-$1.tar.gz.sha256"
  if [ ! -f "$file" ]; then
    echo "missing ${file}" >&2
    exit 1
  fi
  local sum
  sum=$(cut -d ' ' -f 1 "$file")
  if ! [[ "$sum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "${file} does not hold a SHA-256" >&2
    exit 1
  fi
  printf '%s' "$sum"
}

url() {
  printf 'https://github.com/%s/releases/download/%s/fast-proxy-%s-%s.tar.gz' \
    "$repository" "$tag" "$tag" "$1"
}

mac_arm=aarch64-apple-darwin
mac_intel=x86_64-apple-darwin
linux_arm=aarch64-unknown-linux-musl
linux_intel=x86_64-unknown-linux-musl

# Read every checksum before printing: a failure inside the heredoc's command
# substitutions would not stop the script.
mac_arm_sha=$(checksum "$mac_arm")
mac_intel_sha=$(checksum "$mac_intel")
linux_arm_sha=$(checksum "$linux_arm")
linux_intel_sha=$(checksum "$linux_intel")

cat <<FORMULA
# Generated by scripts/homebrew-formula.sh in ${repository}; do not edit by hand.
class FastProxy < Formula
  desc "Fast, realtime-configurable ingress server and reverse proxy"
  homepage "https://github.com/${repository}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url "$mac_arm")"
      sha256 "${mac_arm_sha}"
    end
    on_intel do
      url "$(url "$mac_intel")"
      sha256 "${mac_intel_sha}"
    end
  end

  on_linux do
    on_arm do
      url "$(url "$linux_arm")"
      sha256 "${linux_arm_sha}"
    end
    on_intel do
      url "$(url "$linux_intel")"
      sha256 "${linux_intel_sha}"
    end
  end

  def install
    bin.install "fast-proxy"
    # Homebrew keeps an edited config on upgrade and writes the new one next to it.
    (etc/"fast-proxy").install "config.toml"
  end

  def post_install
    (var/"lib/fast-proxy").mkpath
    (var/"log/fast-proxy").mkpath
  end

  service do
    run [opt_bin/"fast-proxy", "--config", etc/"fast-proxy/config.toml",
         "--state-dir", var/"lib/fast-proxy",
         "--access-log", var/"log/fast-proxy/access.log"]
    working_dir var/"lib/fast-proxy"
    keep_alive true
    log_path var/"log/fast-proxy/fast-proxy.log"
    error_log_path var/"log/fast-proxy/fast-proxy.log"
  end

  def caveats
    <<~EOS
      The configuration is #{etc}/fast-proxy/config.toml; the database and the
      master key are kept in #{var}/lib/fast-proxy when run as a service.
      On first start the admin token is printed to #{var}/log/fast-proxy/fast-proxy.log.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/fast-proxy --version")
    (testpath/"config.toml").write <<~TOML
      [data_plane]
      state_dir = "#{testpath}/state"
    TOML
    system bin/"fast-proxy", "--config", testpath/"config.toml", "config", "validate"
  end
end
FORMULA
