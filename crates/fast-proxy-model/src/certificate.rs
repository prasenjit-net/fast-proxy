//! Certificate identity, limits and the rule for which hosts a certificate
//! covers. No PEM or key types live here: certificate material is never part of
//! the configuration (ADR 0010).

use crate::host_pattern::validate_dns_name;
use crate::{FieldError, HostPattern};

/// Most server certificates that may be stored.
pub const MAX_CERTIFICATES: usize = 256;
/// Most CA bundles that may be stored.
pub const MAX_CA_BUNDLES: usize = 16;
/// Most PEM bytes in one certificate chain or CA bundle.
pub const MAX_PEM_BYTES: usize = 256 * 1024;
/// Most certificates in one chain.
pub const MAX_CHAIN_LENGTH: usize = 10;

const MAX_NAME_LEN: usize = 63;

/// Database id of a stored certificate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct CertificateId(pub i64);

/// The admin-chosen, unique label of a certificate or CA bundle. It appears in
/// metrics and status, so it is restricted to 1-63 characters of `[A-Za-z0-9._-]`
/// starting and ending alphanumeric.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CertificateName(String);

impl CertificateName {
    /// Validates `raw` for the field `name`.
    pub fn parse(raw: &str) -> Result<Self, FieldError> {
        validate_material_name("name", raw)?;
        Ok(Self(raw.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Checks the naming rule for a certificate or CA bundle name under `field`.
pub(crate) fn validate_material_name(field: &str, raw: &str) -> Result<(), FieldError> {
    let invalid = |message: &str| Err(FieldError::new(field, message));
    if raw.is_empty() || raw.len() > MAX_NAME_LEN {
        return invalid("must be 1 to 63 characters");
    }
    if !raw
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
    {
        return invalid("may contain only letters, digits, '.', '_' and '-'");
    }
    let edge = |b: u8| b.is_ascii_alphanumeric();
    if !raw.bytes().next().is_some_and(edge) || !raw.bytes().last().is_some_and(edge) {
        return invalid("must start and end with a letter or digit");
    }
    Ok(())
}

/// Where a certificate came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CertificateSource {
    /// Supplied by the admin.
    Uploaded,
    /// Generated by the proxy for development.
    SelfSigned,
    /// Issued by ACME (M4).
    Acme,
}

impl CertificateSource {
    /// The stored and API spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Uploaded => "uploaded",
            Self::SelfSigned => "self_signed",
            Self::Acme => "acme",
        }
    }

    pub fn parse(raw: &str) -> Result<Self, FieldError> {
        match raw {
            "uploaded" => Ok(Self::Uploaded),
            "self_signed" => Ok(Self::SelfSigned),
            "acme" => Ok(Self::Acme),
            _ => Err(FieldError::new(
                "source",
                "must be uploaded, self_signed or acme",
            )),
        }
    }
}

/// The public facts about a certificate, extracted from its leaf.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CertificateMetadata {
    /// DNS names and wildcards from the SANs, lowercase.
    pub names: Vec<String>,
    pub subject: String,
    pub issuer: String,
    /// Validity start, milliseconds since the epoch.
    pub not_before_ms: i64,
    /// Validity end, milliseconds since the epoch.
    pub not_after_ms: i64,
    /// SHA-256 of the leaf, lowercase hex.
    pub fingerprint: String,
}

impl CertificateMetadata {
    /// Whether any SAN covers `pattern`.
    pub fn covers(&self, pattern: &HostPattern) -> bool {
        self.names.iter().any(|name| covers(name, pattern))
    }
}

/// Whether the certificate name `san` (an exact name or `*.suffix`) covers the
/// host `pattern`: equal names; or a wildcard SAN `*.d` and an exact host with
/// exactly one more label under `d`; a wildcard host pattern `*.d` is covered
/// only by the same wildcard SAN. Comparison ignores case.
pub fn covers(san: &str, pattern: &HostPattern) -> bool {
    let san = san.to_ascii_lowercase();
    match (san.strip_prefix("*."), pattern) {
        (None, HostPattern::Exact(host)) => san == *host,
        (None, HostPattern::Wildcard(_)) => false,
        (Some(suffix), HostPattern::Exact(host)) => host
            .strip_suffix(suffix)
            .and_then(|front| front.strip_suffix('.'))
            .is_some_and(|label| !label.is_empty() && !label.contains('.')),
        (Some(suffix), HostPattern::Wildcard(pattern_suffix)) => suffix == pattern_suffix,
    }
}

/// Validates a SAN entry as stored: an exact DNS name or `*.suffix`.
pub fn validate_san(raw: &str) -> Result<(), FieldError> {
    let name = raw.strip_prefix("*.").unwrap_or(raw);
    validate_dns_name(&name.to_ascii_lowercase())
        .map_err(|err| FieldError::new("names", err.message))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pattern(raw: &str) -> HostPattern {
        HostPattern::parse(raw).unwrap()
    }

    /// The rule restated by splitting labels, to compare against the fast one.
    fn reference(san: &str, host: &str) -> bool {
        let san_labels: Vec<String> = san.to_lowercase().split('.').map(String::from).collect();
        let host_labels: Vec<String> = host.to_lowercase().split('.').map(String::from).collect();
        match (san_labels[0] == "*", host_labels[0] == "*") {
            (false, false) => san_labels == host_labels,
            (false, true) => false,
            (true, true) => san_labels == host_labels,
            (true, false) => {
                host_labels.len() == san_labels.len() && host_labels[1..] == san_labels[1..]
            }
        }
    }

    #[test]
    fn covers_agrees_with_the_reference_over_every_small_combination() {
        let labels = ["a", "b", "A"];
        let mut names = Vec::new();
        for first in labels {
            names.push(first.to_string());
            for second in labels {
                names.push(format!("{first}.{second}"));
                names.push(format!("*.{first}.{second}"));
                names.push(format!("{second}.{first}.{second}"));
            }
            names.push(format!("*.{first}"));
        }
        for san in &names {
            for host in &names {
                let Ok(parsed) = HostPattern::parse(host) else {
                    continue;
                };
                assert_eq!(
                    covers(san, &parsed),
                    reference(san, host),
                    "{san} vs {host}"
                );
            }
        }
    }

    #[test]
    fn named_cases_of_the_coverage_rule() {
        assert!(covers("shop.example.com", &pattern("shop.example.com")));
        assert!(covers("*.example.com", &pattern("shop.example.com")));
        assert!(!covers("*.example.com", &pattern("a.b.example.com")));
        assert!(!covers("*.example.com", &pattern("example.com")));
        assert!(covers("*.example.com", &pattern("*.example.com")));
        assert!(!covers("shop.example.com", &pattern("*.example.com")));
        assert!(!covers("*.example.com", &pattern("*.shop.example.com")));
        assert!(covers("SHOP.example.com", &pattern("shop.EXAMPLE.com")));
    }

    #[test]
    fn metadata_covers_when_any_name_does() {
        let metadata = CertificateMetadata {
            names: vec!["a.example.com".into(), "*.b.example.com".into()],
            subject: String::new(),
            issuer: String::new(),
            not_before_ms: 0,
            not_after_ms: 1,
            fingerprint: String::new(),
        };
        assert!(metadata.covers(&pattern("x.b.example.com")));
        assert!(!metadata.covers(&pattern("c.example.com")));
    }

    #[test]
    fn names_follow_the_rules() {
        for good in ["a", "shop", "dev-shop", "wild.card_1", &"a".repeat(63)] {
            assert!(CertificateName::parse(good).is_ok(), "{good}");
        }
        let long = "a".repeat(64);
        for bad in ["", "-a", "a-", ".a", "a b", "a/b", "né", long.as_str()] {
            assert_eq!(
                CertificateName::parse(bad).unwrap_err().field,
                "name",
                "{bad}"
            );
        }
        assert_eq!(CertificateName::parse("shop").unwrap().as_str(), "shop");
    }

    #[test]
    fn sources_round_trip_and_reject_unknown_values() {
        for source in [
            CertificateSource::Uploaded,
            CertificateSource::SelfSigned,
            CertificateSource::Acme,
        ] {
            assert_eq!(CertificateSource::parse(source.as_str()).unwrap(), source);
        }
        assert_eq!(CertificateSource::parse("x").unwrap_err().field, "source");
    }

    #[test]
    fn limits_match_the_plan() {
        assert_eq!(MAX_CERTIFICATES, 256);
        assert_eq!(MAX_CA_BUNDLES, 16);
        assert_eq!(MAX_PEM_BYTES, 262_144);
        assert_eq!(MAX_CHAIN_LENGTH, 10);
    }

    #[test]
    fn sans_must_be_dns_names_or_wildcards() {
        assert!(validate_san("a.example.com").is_ok());
        assert!(validate_san("*.example.com").is_ok());
        for bad in ["", "a b", "*", "a.*.com", "10.0.0.1"] {
            assert_eq!(validate_san(bad).unwrap_err().field, "names", "{bad}");
        }
    }
}
