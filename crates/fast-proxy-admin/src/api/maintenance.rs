//! Maintenance mode (ADR 0018): turn a whole proxy, a subsystem or one route
//! into a temporary 503 with a message, a TTL and a bypass, and turn it off.
//! Turning on replaces any earlier settings of that scope. A bypass secret is
//! returned once, when it is generated; reads only say that one is set.

use axum::extract::{Path, State};
use axum::Json;
use fast_proxy_auth::{hash_secret, GeneratedSecret};
use fast_proxy_model::{
    BodyContentType, BypassHeader, BypassRules, Cidr, Config, CustomBody, MaintenanceSettings,
    MaintenanceTarget, RouteId, SubsystemId,
};
use fast_proxy_store::repository::load;
use fast_proxy_store::repository::maintenance::MaintenanceRow;
use serde::{Deserialize, Serialize};

use super::change::Change;
use super::envelope::{Envelope, VersionOnly};
use super::input::FieldErrors;
use super::json::ApiJson;
use crate::state::{MaintenanceChange, SharedState};
use crate::{AppError, AppResult};

/// Longest TTL accepted: 30 days.
const MAX_TTL_SECS: u64 = 2_592_000;
/// An operator-chosen bypass secret must be at least this long.
const MIN_SECRET_LEN: usize = 16;

/// Body of the `PUT .../maintenance` routes.
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct MaintenanceRequest {
    #[serde(default)]
    message: String,
    /// A custom response body; needs `contentType`.
    body: Option<String>,
    /// `text/html`, `text/plain` or `application/json`.
    content_type: Option<String>,
    retry_after_secs: Option<u32>,
    /// How long it lasts, in seconds; absent means until turned off.
    ttl_secs: Option<u64>,
    #[serde(default)]
    bypass: BypassRequest,
}

#[derive(Debug, Default, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields, default)]
pub struct BypassRequest {
    /// Source networks that pass, such as `10.0.0.0/8`.
    cidrs: Vec<String>,
    /// A request header whose secret value lets a request pass.
    header: Option<String>,
    /// The secret; generated and returned once when absent.
    secret: Option<String>,
}

/// How a scope's bypass rules read back: never the secret.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BypassDto {
    cidrs: Vec<String>,
    header: Option<String>,
    secret_set: bool,
}

/// One scope as the API shows it.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct MaintenanceDto {
    /// `global`, `subsystem` or `route`.
    scope: &'static str,
    subsystem_id: Option<i64>,
    subsystem: Option<String>,
    route_id: Option<i64>,
    route: Option<String>,
    message: String,
    content_type: Option<&'static str>,
    has_custom_body: bool,
    retry_after_secs: Option<u32>,
    expires_at_ms: Option<i64>,
    seconds_left: Option<i64>,
    set_by: String,
    set_at_ms: i64,
    bypass: BypassDto,
}

/// The response to turning maintenance on.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SetResponse {
    data: MaintenanceDto,
    version: u64,
    /// The generated bypass secret: shown here once and never again.
    bypass_secret: Option<String>,
}

/// `GET /api/maintenance`: every scope that is on right now.
pub async fn list_maintenance(
    State(state): State<SharedState>,
) -> AppResult<Json<Envelope<Vec<MaintenanceDto>>>> {
    let now = crate::clock::now_ms();
    let config = load_config(&state).await?;
    let data = state
        .config
        .list_maintenance()
        .await?
        .into_iter()
        .filter(|row| row.settings.is_active(now))
        .map(|row| dto(&config, &row, now))
        .collect();
    Ok(Json(Envelope {
        data,
        version: state.config.snapshot_holder().load().version,
    }))
}

/// `PUT /api/maintenance/global`
pub async fn set_global(
    State(state): State<SharedState>,
    Change(context): Change,
    ApiJson(body): ApiJson<MaintenanceRequest>,
) -> AppResult<Json<SetResponse>> {
    set(&state, &context, MaintenanceTarget::Global, body).await
}

/// `DELETE /api/maintenance/global`
pub async fn clear_global(
    State(state): State<SharedState>,
    Change(context): Change,
) -> AppResult<Json<VersionOnly>> {
    clear(&state, &context, MaintenanceTarget::Global).await
}

/// `PUT /api/subsystems/{id}/maintenance`
pub async fn set_subsystem(
    State(state): State<SharedState>,
    Change(context): Change,
    Path(id): Path<i64>,
    ApiJson(body): ApiJson<MaintenanceRequest>,
) -> AppResult<Json<SetResponse>> {
    set(
        &state,
        &context,
        MaintenanceTarget::Subsystem(SubsystemId(id)),
        body,
    )
    .await
}

/// `DELETE /api/subsystems/{id}/maintenance`
pub async fn clear_subsystem(
    State(state): State<SharedState>,
    Change(context): Change,
    Path(id): Path<i64>,
) -> AppResult<Json<VersionOnly>> {
    subsystem_config(&load_config(&state).await?, id)?;
    clear(
        &state,
        &context,
        MaintenanceTarget::Subsystem(SubsystemId(id)),
    )
    .await
}

/// `PUT /api/subsystems/{id}/routes/{route_id}/maintenance`
pub async fn set_route(
    State(state): State<SharedState>,
    Change(context): Change,
    Path((id, route_id)): Path<(i64, i64)>,
    ApiJson(body): ApiJson<MaintenanceRequest>,
) -> AppResult<Json<SetResponse>> {
    let target = route_target(&state, id, route_id).await?;
    set(&state, &context, target, body).await
}

/// `DELETE /api/subsystems/{id}/routes/{route_id}/maintenance`
pub async fn clear_route(
    State(state): State<SharedState>,
    Change(context): Change,
    Path((id, route_id)): Path<(i64, i64)>,
) -> AppResult<Json<VersionOnly>> {
    let target = route_target(&state, id, route_id).await?;
    clear(&state, &context, target).await
}

async fn set(
    state: &SharedState,
    context: &fast_proxy_config_service::ChangeContext,
    target: MaintenanceTarget,
    body: MaintenanceRequest,
) -> AppResult<Json<SetResponse>> {
    let (settings, bypass_secret) = settings_from(body)?;
    let applied = state
        .config
        .set_maintenance(context, target, settings)
        .await?;
    let config = load_config(state).await?;
    let now = crate::clock::now_ms();
    let row = state
        .config
        .list_maintenance()
        .await?
        .into_iter()
        .find(|row| row.target == target)
        .ok_or_else(|| AppError::Internal("the scope cannot be read back".into()))?;
    let data = dto(&config, &row, now);
    announce(state, &data, true);
    Ok(Json(SetResponse {
        data,
        version: applied.version,
        bypass_secret,
    }))
}

async fn clear(
    state: &SharedState,
    context: &fast_proxy_config_service::ChangeContext,
    target: MaintenanceTarget,
) -> AppResult<Json<VersionOnly>> {
    let config = load_config(state).await?;
    let before = state
        .config
        .list_maintenance()
        .await?
        .into_iter()
        .find(|row| row.target == target);
    let applied = state.config.clear_maintenance(context, target).await?;
    if let (true, Some(row)) = (applied.value, before) {
        announce(state, &dto(&config, &row, crate::clock::now_ms()), false);
    }
    Ok(Json(VersionOnly {
        version: applied.version,
    }))
}

fn announce(state: &SharedState, scope: &MaintenanceDto, active: bool) {
    state.maintenance_changed(MaintenanceChange {
        scope: scope.scope,
        subsystem: scope.subsystem.as_deref(),
        route: scope.route.as_deref(),
        active,
        expires_at_ms: scope.expires_at_ms,
    });
}

async fn load_config(state: &SharedState) -> AppResult<Config> {
    Ok(state.config.read(load::load_all).await?.value)
}

/// The subsystem `id`, or a 404.
fn subsystem_config(config: &Config, id: i64) -> AppResult<&fast_proxy_model::SubsystemConfig> {
    config
        .subsystems
        .iter()
        .find(|candidate| candidate.id == SubsystemId(id))
        .ok_or_else(|| AppError::NotFound(format!("subsystem {id} not found")))
}

/// The route target, after checking the route belongs to the subsystem.
async fn route_target(
    state: &SharedState,
    subsystem: i64,
    route: i64,
) -> AppResult<MaintenanceTarget> {
    let config = load_config(state).await?;
    let subsystem_config = subsystem_config(&config, subsystem)?;
    if !subsystem_config
        .routes
        .iter()
        .any(|r| r.id == RouteId(route))
    {
        return Err(AppError::NotFound(format!(
            "route {route} not found in subsystem {subsystem}"
        )));
    }
    Ok(MaintenanceTarget::Route(RouteId(route)))
}

/// Validates the request and builds the settings. Returns the bypass secret
/// that was generated, when the request asked for a header without one.
fn settings_from(body: MaintenanceRequest) -> AppResult<(MaintenanceSettings, Option<String>)> {
    let mut errors = FieldErrors::default();
    let cidrs: Vec<Cidr> = body
        .bypass
        .cidrs
        .iter()
        .filter_map(|raw| errors.check(Cidr::parse("bypass.cidrs", raw.trim())))
        .collect();

    let body_text = match (body.body, body.content_type) {
        (None, None) => None,
        (Some(text), Some(kind)) => errors
            .check(BodyContentType::parse(&kind))
            .map(|content_type| CustomBody { content_type, text }),
        (Some(_), None) => {
            errors.add("contentType", "is required with a custom body");
            None
        }
        (None, Some(_)) => {
            errors.add("body", "is required with a content type");
            None
        }
    };
    if body
        .ttl_secs
        .is_some_and(|ttl| ttl == 0 || ttl > MAX_TTL_SECS)
    {
        errors.add("ttlSecs", "must be between 1 and 2592000 (30 days)");
    }

    let mut generated = None;
    let header = match (body.bypass.header, body.bypass.secret) {
        (None, None) => None,
        (None, Some(_)) => {
            errors.add(
                "bypass.secret",
                "needs bypass.header: name the header it goes in",
            );
            None
        }
        (Some(name), secret) => {
            let hash = match secret {
                Some(secret) if secret.len() < MIN_SECRET_LEN => {
                    errors.add("bypass.secret", "must be at least 16 characters");
                    None
                }
                Some(secret) => Some(hash_secret(&secret)),
                None => {
                    let made = GeneratedSecret::generate()
                        .map_err(|err| AppError::Internal(err.to_string()))?;
                    generated = Some(made.value().to_string());
                    Some(made.hash().clone())
                }
            };
            hash.map(|secret_hash| BypassHeader {
                name: name.trim().to_string(),
                secret_hash,
            })
        }
    };
    errors.finish()?;

    let now = crate::clock::now_ms();
    let settings = MaintenanceSettings {
        message: body.message,
        body: body_text,
        retry_after_secs: body.retry_after_secs,
        bypass: BypassRules { cidrs, header },
        expires_at_ms: body
            .ttl_secs
            .map(|ttl| now + i64::try_from(ttl).unwrap_or(i64::MAX) * 1000),
        set_by: String::new(),
        set_at_ms: now,
    };
    settings
        .validate()
        .map_err(|err| AppError::Validation(vec![err]))?;
    Ok((settings, generated))
}

/// A stored scope as the API shows it, with the names of what it covers.
fn dto(config: &Config, row: &MaintenanceRow, now_ms: i64) -> MaintenanceDto {
    let (scope, subsystem_id, route_id) = match row.target {
        MaintenanceTarget::Global => ("global", None, None),
        MaintenanceTarget::Subsystem(id) => ("subsystem", Some(id), None),
        MaintenanceTarget::Route(id) => (
            "route",
            config
                .subsystems
                .iter()
                .find(|s| s.routes.iter().any(|r| r.id == id))
                .map(|s| s.id),
            Some(id),
        ),
    };
    let subsystem = subsystem_id.and_then(|id| config.subsystems.iter().find(|s| s.id == id));
    let route = route_id.and_then(|id| {
        subsystem
            .and_then(|s| s.routes.iter().find(|r| r.id == id))
            .map(|r| r.prefix.as_str().to_string())
    });
    let settings = &row.settings;
    MaintenanceDto {
        scope,
        subsystem_id: subsystem_id.map(|id| id.0),
        subsystem: subsystem.map(|s| s.name.as_str().to_string()),
        route_id: route_id.map(|id| id.0),
        route,
        message: settings.message.clone(),
        content_type: settings.body.as_ref().map(|b| b.content_type.as_str()),
        has_custom_body: settings.body.is_some(),
        retry_after_secs: settings.retry_after_secs,
        expires_at_ms: settings.expires_at_ms,
        seconds_left: settings
            .expires_at_ms
            .map(|at| (at - now_ms).div_euclid(1000).max(0)),
        set_by: settings.set_by.clone(),
        set_at_ms: settings.set_at_ms,
        bypass: BypassDto {
            cidrs: settings
                .bypass
                .cidrs
                .iter()
                .map(Cidr::to_cidr_string)
                .collect(),
            header: settings.bypass.header.as_ref().map(|h| h.name.clone()),
            secret_set: settings.bypass.header.is_some(),
        },
    }
}
